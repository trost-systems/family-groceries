// Writes the Supabase Auth templates from src/emails/auth.tsx: supabase/templates/<template>.html,
// a .txt twin and subjects.json.
//   npx tsx scripts/build.tsx               write
//   npx tsx scripts/build.tsx --check       write nothing, exit 1 when a file differs (CI)
//   npx tsx scripts/build.tsx --production  render every mail as for sending; exit 1 while a
//                                           draft line or the demo unsubscribe link is in one
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EmailRenderError, renderEmail } from '../src/render.ts';
import { EMAILS } from '../src/registry.tsx';

const CONFIG = fileURLToPath(new URL('../../supabase/config.toml', import.meta.url));
export const TEMPLATES_DIR = fileURLToPath(new URL('../../supabase/templates/', import.meta.url));
const BANNER = '<!-- generated from emails/ (cd emails && npm run build), do not edit -->';

export async function templateFiles(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const subjects: Record<string, string> = {};
  for (const email of EMAILS) {
    if (!email.template) continue;
    const { html, text } = await renderEmail(email.element);
    files.set(`${email.template}.html`, html.replace(/^(<!DOCTYPE[^>]*>)/, `$1\n${BANNER}\n`));
    files.set(`${email.template}.txt`, text);
    subjects[email.template] = email.subject;
  }
  files.set('subjects.json', `${JSON.stringify(subjects, null, 2)}\n`);
  return files;
}

// The local stack sends the same templates (Mailpit shows them). The security notifications
// stay off, as on the hosted project.
const BEGIN = '# BEGIN auth mail templates (generated by emails/scripts/build.tsx, do not edit)';
const END = '# END auth mail templates';
export function configToml(current: string): string {
  const blocks = EMAILS.filter((e) => e.template).map(({ template, subject }) => {
    const notification = template!.endsWith('_notification');
    const key = notification ? `notification.${template!.replace(/_notification$/, '')}` : `template.${template}`;
    return [`[auth.email.${key}]`, ...(notification ? ['enabled = false'] : []), `subject = ${JSON.stringify(subject)}`, `content_path = "./supabase/templates/${template}.html"`].join('\n');
  });
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) throw new Error(`supabase/config.toml lacks the "${BEGIN}" ... "${END}" markers`);
  return `${current.slice(0, start)}${BEGIN}\n${blocks.join('\n\n')}\n${current.slice(end)}`;
}

async function main(mode: string | undefined) {
  if (mode === '--production') {
    const refused: string[] = [];
    for (const email of EMAILS) {
      try {
        await renderEmail(email.element, { production: true });
      } catch (e) {
        if (!(e instanceof EmailRenderError)) throw e;
        refused.push(`${email.id}: ${e.message}`);
      }
    }
    if (refused.length) {
      console.error(`not ready to send:\n  ${refused.join('\n  ')}`);
      process.exit(1);
    }
    console.log('every mail renders for production');
    return;
  }
  const files = await templateFiles();
  const config = readFileSync(CONFIG, 'utf8');
  if (mode === '--check') {
    if (configToml(config) !== config) {
      console.error('supabase/config.toml\'s auth mail templates are not what emails/ builds (run: cd emails && npm run build)');
      process.exit(1);
    }
    const stale = [...files].filter(([name, content]) => !existsSync(join(TEMPLATES_DIR, name)) || readFileSync(join(TEMPLATES_DIR, name), 'utf8') !== content).map(([n]) => n);
    const extra = existsSync(TEMPLATES_DIR) ? readdirSync(TEMPLATES_DIR).filter((n) => !files.has(n)) : [];
    if (stale.length || extra.length) {
      console.error(`supabase/templates/ is not what emails/ builds (run: cd emails && npm run build):\n  ${[...stale, ...extra.map((n) => `${n} (not built from emails/)`)].join('\n  ')}`);
      process.exit(1);
    }
    console.log(`supabase/templates/ matches emails/ (${files.size} files)`);
    return;
  }
  mkdirSync(TEMPLATES_DIR, { recursive: true });
  for (const [name, content] of files) writeFileSync(join(TEMPLATES_DIR, name), content);
  writeFileSync(CONFIG, configToml(config));
  console.log(`wrote ${files.size} files to supabase/templates/ and the templates in supabase/config.toml`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main(process.argv[2]);
