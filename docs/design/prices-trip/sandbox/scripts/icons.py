"""Writes src/generated/icons.ts: SVG paths of the app's Material icons, read from Flutter's font.

Run with fontTools on the path (the PyPI wheel unzipped is enough):
  PYTHONPATH=<unzipped wheel> python3 scripts/icons.py
"""
import json
import os
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

NAMES = [
    'add', 'remove', 'check', 'close', 'edit_outlined', 'backspace_outlined', 'expand_more',
    'chevron_right', 'chevron_left', 'arrow_back', 'undo', 'history', 'error_outline',
    'shopping_cart_outlined', 'scale_outlined', 'receipt_long_outlined', 'menu', 'mic_none', 'done_all', 'euro',
]

flutter = os.path.expanduser('~/flutter')
font = TTFont(f'{flutter}/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf')
source = open(f'{flutter}/packages/flutter/lib/src/material/icons.dart').read()
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
upm = font['head'].unitsPerEm
out = {}
for name in NAMES:
    m = re.search(rf'static const IconData {name} = IconData\(\s*(0x[0-9a-f]+)', source)
    if not m:
        sys.exit(f'no codepoint for {name}')
    pen = SVGPathPen(glyphs)
    s = 24 / upm
    glyphs[cmap[int(m.group(1), 16)]].draw(TransformPen(pen, (s, 0, 0, -s, 0, 24)))
    out[name] = pen.getCommands()

here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(f'{here}/../src/generated', exist_ok=True)
with open(f'{here}/../src/generated/icons.ts', 'w') as f:
    f.write('// Generated by scripts/icons.py from Flutter\'s MaterialIcons-Regular.otf. Do not edit.\n')
    f.write(f'export const icons = {json.dumps(out, indent=2)} as const\n\n')
    f.write('export type IconName = keyof typeof icons\n')
print(f'{len(out)} icons')
