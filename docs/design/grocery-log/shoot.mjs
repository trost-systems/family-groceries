// Drives the four shared scenarios through every approach, checks what the phone shows and writes screenshots.
// Usage: node shoot.mjs <page-url> <out-dir> [playwright-module-dir]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import process from 'node:process';

const [url, out, pwDir = `${process.env.HOME}/family-groceries/e2e/node_modules/`] = process.argv.slice(2);
const { chromium } = createRequire(pwDir)('playwright');
mkdirSync(out, { recursive: true });

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 900, height: 860 }, deviceScaleFactor: 2, locale: 'de-DE', timezoneId: 'Europe/Berlin' });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (msg) => msg.type() === 'error' && errors.push(msg.text()));
const phone = page.locator('.phone');
const failures = [];
process.on('uncaughtException', (e) => {
  console.log([...failures, `stopped: ${e.message.split('\n')[0]}`].join('\n\n'));
  process.exit(1);
});
const expect = async (label, text, present = true) => {
  const got = await phone.innerText();
  if (got.includes(text) !== present) failures.push(`${label}: ${present ? 'missing' : 'unexpected'} "${text}"\n---\n${got}\n---`);
};
const open = async (a, s = 'history') => {
  await page.goto(`${url}#a=${a}&s=${s}`);
  await page.reload();
  await page.evaluate(() => document.fonts.ready);
};
const shot = (name) => phone.screenshot({ path: `${out}/${name}.png` });
const tap = (name, exact = false) => phone.getByRole('button', { name, exact }).first().click();
const type = async (text) => {
  await phone.getByRole('textbox', { name: 'Artikel hinzufügen' }).fill(text);
  await phone.getByRole('textbox', { name: 'Artikel hinzufügen' }).press('Enter');
};
const milkAndBread = async (a) => {
  await type('Milch');
  const field = phone.getByRole('textbox', { name: 'Artikel hinzufügen' });
  await field.fill('Brot');
  await tap('Heute', true);
  if ((await field.inputValue()) !== 'Brot') failures.push(`${a}: a chip tap cleared the typed item`);
  await shot(`${a}--1-record-sheet`);
  await tap('Speichern', true);
  const today = await phone.locator('button[aria-label^="Donnerstag, 12. November"]').evaluateAll((els) => els.map((e) => e.ariaLabel));
  if (!today.some((l) => l.endsWith(', Milch, Brot'))) failures.push(`${a}: typed item not saved without Enter: ${today}`);
};
const editTrip = async (a, label) => {
  await tap('Bearbeiten');
  await phone.getByRole('textbox', { name: 'Menge 1' }).fill('3');
  await type('Sahne');
  await shot(`${a}--3-edit-sheet`);
  await tap('Speichern', true);
  await expect(`${a} edit`, 'Sahne');
  await expect(`${a} edit`, 'Änderungen gespeichert');
  await expect(`${a} edit qty`, label);
  await shot(`${a}--3-edit-saved`);
};
const emptyHistory = async (a, text) => {
  await open(a, 'empty');
  if (a === 'post-shop-entry-sheet') await tap(/^Verlauf/);
  await expect(`${a} empty`, text);
  await expect(`${a} empty free`, 'kostenlos');
  await shot(`${a}--4-empty`);
};

let a = 'trip-journal-by-date';
await open(a);
await shot(`${a}--0-home`);
await tap('Einkauf eintragen');
await tap('Rewe', true);
await milkAndBread(a);
await expect(`${a} record`, 'Heute · Rewe');
await expect(`${a} record`, 'Milch, Brot');
await expect(`${a} record section`, 'Diese Woche');
await shot(`${a}--1-recorded`);
await phone.locator('.body').evaluate((b) => b.scrollTo(0, b.scrollHeight));
await shot(`${a}--2-scrolled`);
await tap(/^Samstag, 31. Oktober, Rewe/);
await expect(`${a} toast left behind`, 'Einkauf bei Rewe eingetragen', false);
await expect(`${a} browse`, 'Butter');
await shot(`${a}--2-trip`);
await editTrip(a, '3');
await tap('Bearbeiten');
await tap('Löschen');
await expect(`${a} delete`, 'Einkauf gelöscht');
await expect(`${a} delete gone`, 'Sa., 31. Okt. · Rewe', false);
await tap('Rückgängig');
await expect(`${a} undo`, 'Sa., 31. Okt. · Rewe');
await emptyHistory(a, 'Noch keine Einkäufe');

a = 'store-timeline';
await open(a);
await shot(`${a}--0-home`);
await tap('Einkauf bei Rewe eintragen');
await milkAndBread(a);
await expect(`${a} record`, 'Einkauf bei Rewe eingetragen');
await expect(`${a} record`, 'Milch, Brot');
await expect(`${a} record count`, '4 Einkäufe · zuletzt heute');
await shot(`${a}--1-recorded`);
await tap(/^Aldi Süd/);
await shot(`${a}--2-store-open`);
await tap(/^Dienstag, 27. Oktober/);
await expect(`${a} browse`, 'Reis');
await shot(`${a}--2-trip`);
await editTrip(a, '3');
await emptyHistory(a, 'Noch nichts eingetragen');

a = 'post-shop-entry-sheet';
await open(a);
await shot(`${a}--0-home`);
await tap('Milch abhaken');
await expect(`${a} no prompt mid-shop`, 'Einkauf bei Rewe eintragen?', false);
await tap('Brot abhaken');
await expect(`${a} prompt`, 'Einkauf bei Rewe eintragen?');
await shot(`${a}--1-prompt`);
await tap('Eintragen', true);
await expect(`${a} prefill`, 'Aus deinen Häkchen von heute');
const prefilled = await phone.getByRole('textbox', { name: /^Artikel \d/ }).evaluateAll((els) => els.map((e) => e.value));
if (prefilled.join() !== 'Milch,Brot') failures.push(`${a} prefill: ${prefilled}`);
await shot(`${a}--1-record-sheet`);
await tap('Speichern', true);
await expect(`${a} record`, 'Einkauf bei Rewe eingetragen');
await expect(`${a} list cleared`, 'Abgehakt', false);
await shot(`${a}--1-recorded`);
await tap(/^Verlauf/);
await expect(`${a} history`, 'Heute · Rewe');
await shot(`${a}--2-history`);
await tap(/^Samstag, 31. Oktober, Rewe/);
await expect(`${a} browse`, 'Kaffee');
await editTrip(a, '3');
await open(a);
await tap('Milch abhaken');
await tap('Brot abhaken');
await tap('Eintragen', true);
await tap('Aldi Süd', true);
await tap('Speichern', true);
await expect(`${a} store changed: ticks cleared`, 'Abgehakt', false);
await expect(`${a} store changed: prompt gone`, 'Einkauf bei Rewe eintragen?', false);
await emptyHistory(a, 'Hak auf der Liste ab');

a = 'calendar-trip-browse';
await open(a);
await shot(`${a}--0-home`);
await tap('Einkauf von heute eintragen');
await tap('Rewe', true);
await milkAndBread(a);
await expect(`${a} record`, 'Donnerstag, 12. November');
await expect(`${a} record`, 'Milch, Brot');
await shot(`${a}--1-recorded`);
await tap('Vorheriger Monat');
await expect(`${a} month change picks a day in that month`, 'Samstag, 31. Oktober');
await tap('Samstag, 24. Oktober, 1 Einkauf');
await shot(`${a}--2-day`);
await tap(/^Samstag, 24. Oktober, Wochenmarkt/);
await expect(`${a} browse`, 'Kartoffeln');
await shot(`${a}--2-trip`);
await editTrip(a, '3');
await tap('Zurück');
await tap('Montag, 19. Oktober');
await expect(`${a} empty day`, 'An diesem Tag ist nichts eingetragen');
await tap('Einkauf vom 19. Okt. eintragen');
await tap('Rewe', true);
await type('Mehl');
await tap('Speichern', true);
await expect(`${a} backfill`, 'Mehl');
await emptyHistory(a, 'Wähl einen Tag');

a = 'relist-from-past-trip';
await open(a);
await shot(`${a}--0-home`);
await tap('Einkauf eintragen');
await tap('Rewe', true);
await milkAndBread(a);
await expect(`${a} record`, 'Heute · Rewe');
await tap(/^Samstag, 31. Oktober, Rewe/);
await expect(`${a} already`, 'steht schon drauf');
await expect(`${a} pick`, '1 Artikel auf die Liste');
await shot(`${a}--2-trip`);
await tap('1 Artikel auf die Liste');
await expect(`${a} relisted`, '1 Artikel auf die Liste gesetzt');
await expect(`${a} relisted badge`, 'Liste (5)');
await tap(/^Liste/);
await expect(`${a} list`, 'Kaffee');
await shot(`${a}--2-relisted-list`);
await tap(/^Verlauf/);
await tap(/^Samstag, 31. Oktober, Rewe/);
await editTrip(a, '3');
await expect(`${a} pick after edit`, '1 Artikel auf die Liste');
await emptyHistory(a, 'wieder auf die Liste');

await page.setViewportSize({ width: 1440, height: 900 });
await open('trip-journal-by-date');
await page.evaluate(() => scrollTo(0, 0));
await page.screenshot({ path: `${out}/index.png` });

await browser.close();
if (errors.length) failures.push(`page errors:\n${errors.join('\n')}`);
console.log(failures.length ? failures.join('\n\n') : 'all scenarios pass in all five approaches, 0 page errors');
process.exit(failures.length ? 1 : 0);
