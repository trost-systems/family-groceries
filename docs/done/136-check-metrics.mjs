import { createRequire } from 'node:module';
const require = createRequire('/home/agents/family-groceries/e2e/package.json');
const { chromium, devices } = require('playwright');
const csp = JSON.parse(require('fs').readFileSync('/home/agents/fg-wt/136-bottom-nav-prototypes/site/vercel.json','utf8')).headers[0].headers.find(h=>h.key==='Content-Security-Policy').value;
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type()==='error' && errs.push(m.text()));
await p.route('**/*', async (r) => { const res = await r.fetch(); await r.fulfill({ response: res, headers: { ...res.headers(), 'content-security-policy': csp } }); });
const url = process.argv[2];
const metrics = () => p.$$eval('[data-metric]', (els) => els.map((e) => e.textContent));
const fresh = async (clicks) => { await p.goto(url, { waitUntil: 'networkidle' }); for (const c of clicks) await p.click(c); await p.waitForTimeout(300); return metrics(); };
const toggles = ['[data-control=lang] [data-value=en]', '[data-control=theme] [data-value=dark]'];
const expected = await fresh(toggles);
await p.goto(url, { waitUntil: 'networkidle' });
await p.$$eval('.content', (els) => els.forEach((e) => { e.scrollTop = 200; }));
for (const v of ['current', 'compact', 'pill', 'island']) await p.click(`.phone[data-variant=${v}] .tab[data-tab=more]`);
await p.click('.phone[data-variant=inline] .nav');
await p.$$eval('.content', (els) => els.forEach((e) => { e.scrollTop = 120; }));
for (const c of toggles) await p.click(c);
await p.waitForTimeout(300);
await p.$$eval('.content', (els) => els.forEach((e) => { e.scrollTop = 150; }));
await p.setViewportSize({ width: 360, height: 740 });
await p.waitForTimeout(300);
const got = await metrics();
const tabs = await p.$$eval('.phone', (els) => els.map((e) => e.dataset.tab));
console.log('expected', expected);
console.log('after More + scroll + EN + Dark', got, tabs);
const ok = JSON.stringify(got) === JSON.stringify(expected) && tabs.every((t) => t === 'more');
await p.screenshot({ path: '/tmp/job136/more-then-toggle.png', fullPage: true });
console.log(ok ? 'PASS metrics stable' : 'FAIL metrics differ', 'errors', errs);
await b.close(); process.exit(ok ? 0 : 1);
