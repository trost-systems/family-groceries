// The site's generated tokens.css follows prefers-color-scheme only. The dashboard also has a
// theme toggle, so this derives a copy where `data-theme` on <html> wins over the system setting.
//   deno run --allow-read --allow-write scripts/theme.ts <site/public/tokens.css> <out.css>

/** The declarations inside the first `selector {` block after `from`. */
function block(css: string, from: number): { body: string; end: number } {
  const open = css.indexOf('{', css.indexOf(':root', from));
  const close = css.indexOf('}', open);
  if (open < 0 || close < 0) throw new Error('tokens.css: no :root block');
  return { body: css.slice(open + 1, close).trim(), end: close };
}

export function themeCss(tokensCss: string): string {
  const light = block(tokensCss, 0);
  const media = tokensCss.indexOf('@media (prefers-color-scheme: dark)', light.end);
  if (media < 0) throw new Error('tokens.css: no dark block');
  const dark = block(tokensCss, media).body;
  return [
    '/* Generated by nexus/scripts/theme.ts from site/public/tokens.css. Do not edit. */',
    `:root {\n  ${light.body}\n}`,
    `:root[data-theme="dark"] {\n  color-scheme: dark;\n  ${dark}\n}`,
    `:root[data-theme="light"] {\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n  ${dark}\n  }\n}`,
    '',
  ].join('\n\n');
}

if (import.meta.main) {
  const [input, output] = Deno.args;
  if (input === undefined || output === undefined) throw new Error('usage: theme.ts <tokens.css> <out.css>');
  await Deno.writeTextFile(output, themeCss(await Deno.readTextFile(input)));
}
