#!/usr/bin/env node
// Writes hc-memory-300.yaml: one user alone in a household with 300 open items. Seeded, so reruns write the same file.
import { writeFileSync } from 'node:fs';

const SEED = 107;
let state = SEED;
const rand = () => {
  state = (state + 0x6d2b79f5) | 0;
  let t = Math.imul(state ^ (state >>> 15), 1 | state);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (xs) => xs[Math.floor(rand() * xs.length)];

const BASE = `Äpfel Bananen Birnen Zitronen Kartoffeln Zwiebeln Knoblauch Paprika Brokkoli Salat Tomaten Avocado Gurken
Karotten Zucchini Pilze Trauben Erdbeeren Orangen Mandarinen Spinat Lauch Kohlrabi Vollkornbrot Brötchen
Toastbrot Croissants Baguette Knäckebrot Brezeln Milch Butter Joghurt Quark Gouda Mozzarella Frischkäse Eier Sahne
Schmand Parmesan Feta Hähnchenbrust Hackfleisch Lachs Salami Kochschinken Putenbrust Bratwurst Thunfisch Nudeln Reis
Mehl Zucker Haferflocken Linsen Kichererbsen Tomatenmark Olivenöl Essig Senf Ketchup Honig Marmelade Müsli Cornflakes
Kaffee Tee Kakao Schokolade Kekse Chips Gummibärchen Nüsse Mineralwasser Apfelsaft Orangensaft Bier Wein Limonade
Tiefkühlpizza Erbsen Pommes Vanilleeis Fischstäbchen Spülmittel Müllbeutel Alufolie Küchenrolle Waschmittel
Toilettenpapier Schwämme Zahnpasta Duschgel Shampoo Deo Taschentücher Seife Batterien Kerzen`.split(/\s+/);
const FORMS = [(n) => n, (n) => `${n} Bio`, (n) => `${n} groß`];
const QUANTITIES = [null, null, null, '1', '2', '3', '6', '500 g', '1 kg', '2 l'];
const STORES = [null, null, 'Supermarkt', 'Wochenmarkt', 'Drogerie'];

const items = [];
for (const form of FORMS) for (const base of BASE) items.push(form(base));
if (items.length !== 300) throw new Error(`expected 300 items, got ${items.length}`);

const line = (name) => {
  const quantity = pick(QUANTITIES);
  const store = pick(STORES);
  const parts = [`name: ${name}`];
  if (quantity) parts.push(`quantity: "${quantity}"`);
  if (store) parts.push(`store: ${store}`);
  return `      - { ${parts.join(', ')} }`;
};

const yaml = `# yaml-language-server: $schema=../../../test/fixtures/scenario.schema.json
# Generated by gen-scenario.mjs (seed ${SEED}); do not edit by hand.
name: hc-memory-300
summary: One person alone in a household with 300 open items over three stores and no store, for the hc-memory hill climb.
goodFor:
  - memory and scrolling on a large list
users:
  - { handle: hc, name: Hanna Climb }
households:
  - name: Hannas Liste
    members: [hc]
    stores:
      - name: Supermarkt
      - name: Wochenmarkt
      - name: Drogerie
    items:
${items.map(line).join('\n')}
`;
writeFileSync(new URL('./hc-memory-300.yaml', import.meta.url), yaml);
console.log(`seed ${SEED}: ${items.length} items`);
