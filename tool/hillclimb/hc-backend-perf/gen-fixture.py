"""Writes the hc-backend-perf fixture: a scenario for `fg seed` (300 open items, 5,000 bought in
the last year) and the names the workload adds, from the classifier dictionary with a fixed seed.

Run from the repo root: python3 -I tool/hillclimb/hc-backend-perf/gen-fixture.py
"""
import json
import random
import re
import sys

SEED = 106
here = 'tool/hillclimb/hc-backend-perf'

terms = []
with open('supabase/classifier/dictionary.tsv', encoding='utf-8') as f:
    for line in f:
        if line.startswith('#') or not line.strip():
            continue
        term = line.split('\t')[0].strip()
        if re.fullmatch(r'[A-Za-zÄÖÜäöüß]{3,}', term):
            terms.append(term[0].upper() + term[1:])
terms = sorted(set(terms))
random.Random(SEED).shuffle(terms)

supermarkt, wochenmarkt, drogerie = terms[0:50], terms[50:80], terms[80:100]
once = terms[100:420]
fresh = terms[420:570]
adds = terms[570:]
open_items = random.Random(SEED + 1).sample(terms[0:420], 150) + fresh
random.Random(SEED + 2).shuffle(open_items)

def flow(names):
    return '[' + ', '.join(names) + ']'

out = [
    '# yaml-language-server: $schema=../../../test/fixtures/scenario.schema.json',
    '# Generated by gen-fixture.py (seed 106). Do not edit by hand.',
    'name: hc-backend-perf',
    'summary: Two members with 300 open items and 5,000 bought over the last year at three stores, the load fixture of the hc-backend-perf hill climb.',
    'users:',
    '  - { handle: ann, name: Ann Perf }',
    '  - { handle: ben, name: Ben Perf }',
    'households:',
    '  - name: Haushalt Perf',
    '    members: [ann, ben]',
    '    stores:',
    '      - name: Supermarkt',
    '      - name: Wochenmarkt',
    '      - name: Drogerie',
    '    items:',
]
stores = [None, None, 'Supermarkt', 'Wochenmarkt', 'Drogerie']
pick = random.Random(SEED + 3)
for i, name in enumerate(open_items):
    store = pick.choice(stores)
    by = 'ann' if i % 2 == 0 else 'ben'
    fields = [f'name: {name}', f'by: {by}']
    if store:
        fields.append(f'store: {store}')
    if i % 7 == 0:
        fields.append('quantity: "2"')
    out.append('      - { ' + ', '.join(fields) + ' }')
out.append('    history:')
# 52 weekly trips each: 50 + 30 names; 26 fortnightly: 20 names; 32 single trips of 10: 320.
out += [
    '      - { at: "-3d 17:30", by: ann, store: Supermarkt, every: 7d, times: 52, items: ' + flow(supermarkt) + ' }',
    '      - { at: "-5d 10:00", by: ben, store: Wochenmarkt, every: 7d, times: 52, items: ' + flow(wochenmarkt) + ' }',
    '      - { at: "-8d 18:00", by: ben, store: Drogerie, every: 14d, times: 26, items: ' + flow(drogerie) + ' }',
]
for t in range(32):
    chunk = once[t * 10:(t + 1) * 10]
    out.append(f'      - {{ at: "-{11 * t + 2}d 12:00", by: {"ann" if t % 2 else "ben"}, items: {flow(chunk)} }}')
total = 52 * 50 + 52 * 30 + 26 * 20 + 320
assert total == 5000, total
assert len(open_items) == 300 and len(set(open_items)) == 300

with open(f'{here}/hc-backend-perf.yaml', 'w', encoding='utf-8') as f:
    f.write('\n'.join(out) + '\n')
with open(f'{here}/adds.json', 'w', encoding='utf-8') as f:
    json.dump({'seed': SEED, 'names': adds}, f, ensure_ascii=False, indent=0)
    f.write('\n')
print(f'{len(open_items)} open, {total} bought, {len(adds)} add names', file=sys.stderr)
