#!/usr/bin/env bash
# Job 61: writes app/lib/list/lexicon_forms.dart, the classifier's word forms
# (public.classifier_lexicon: dictionary terms and synonyms, folded) for the app, which checks a
# typed name against them offline before it reads a bare number at the end as the Menge. With
# --check (the db gate) it fails when the file is not what this stack's migrations give.
# CLASSIFIER_PSQL="psql -h ... -d ..." runs it against another database (default: the local stack).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
target="$here/../../app/lib/list/lexicon_forms.dart"
project_id="$(sed -n 's/^project_id = "\(.*\)"$/\1/p' "$here/../config.toml")"
db() {
  if [[ -n ${CLASSIFIER_PSQL:-} ]]; then $CLASSIFIER_PSQL "$@"; else docker exec -i "supabase_db_$project_id" psql -U postgres "$@"; fi
}
forms="$(db -v ON_ERROR_STOP=1 -At -c "select form from public.classifier_lexicon group by form order by form collate \"C\"")"
generated="$(
  echo '// Generated by supabase/classifier/client_lexicon.sh from public.classifier_lexicon.'
  echo '// Do not edit; rerun the script after a classifier migration.'
  echo
  echo '/// The forms public.classifier_words matches, as public.item_key and'
  echo '/// public.fold_key write them.'
  echo 'const lexiconForms = {'
  while IFS= read -r form; do echo "  '$form',"; done <<<"$forms"
  echo '};'
)"
if [[ ${1:-} == --check ]]; then
  if ! diff -u "$target" - <<<"$generated" >/dev/null; then
    echo "app/lib/list/lexicon_forms.dart is out of date: run supabase/classifier/client_lexicon.sh" >&2
    exit 1
  fi
  echo "lexicon_forms.dart matches public.classifier_lexicon ($(wc -l <<<"$forms") forms)"
else
  printf '%s\n' "$generated" >"$target"
  echo "wrote $target ($(wc -l <<<"$forms") forms)"
fi
