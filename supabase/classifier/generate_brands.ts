// Turns brands.tsv into the migration that loads public.brands.
// Usage: deno run --allow-read --allow-write generate_brands.ts <migration.sql>
// Create the migration first (`supabase migration new classifier_brands`); a migration already
// on main is never edited.

export const storeSeeds = ["dm", "lidl", "edeka"] as const;

export type StoreSeed = typeof storeSeeds[number];
export type Brand = {
  brand: string;
  product: string | null;
  store: StoreSeed | null;
};

/** public.brand_key: case, umlauts, accents, spaces, dots, hyphens and apostrophes fold away. */
export function brandKey(brand: string): string {
  return brand.toLowerCase()
    .replaceAll("ä", "a").replaceAll("ö", "o").replaceAll("ü", "u").replaceAll(
      "ß",
      "ss",
    )
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replaceAll("ae", "a").replaceAll("oe", "o").replaceAll("ue", "u")
    .replace(/[\s.'’´`-]+/g, "");
}

export function parseBrands(tsv: string): Brand[] {
  const seen = new Map<string, number>();
  const brands: Brand[] = [];
  tsv.split("\n").forEach((raw, index) => {
    const line = raw.trimEnd();
    const at = `brands.tsv:${index + 1}`;
    if (line === "" || line.startsWith("#")) return;
    const fields = line.split("\t");
    if (fields.length > 3) {
      throw new Error(`${at}: expected "brand<TAB>product<TAB>store"`);
    }
    const [brand, product = "", store = ""] = fields;
    if (brand !== brand.trim() || brand.length < 1 || brand.length > 60) {
      throw new Error(`${at}: invalid brand "${brand}"`);
    }
    // The parser reads a leading number as the Menge ("3 Glocken" would be 3 x "Glocken").
    if (/^\d+([.,]\d+)?\s/.test(brand)) {
      throw new Error(`${at}: "${brand}" starts with an amount`);
    }
    if (product !== product.trim() || product.length > 120) {
      throw new Error(`${at}: invalid product "${product}"`);
    }
    if (store !== "" && !(storeSeeds as readonly string[]).includes(store)) {
      throw new Error(`${at}: unknown store "${store}"`);
    }
    const key = brandKey(brand);
    const first = seen.get(key);
    if (first !== undefined) {
      throw new Error(`${at}: "${brand}" repeats line ${first}`);
    }
    seen.set(key, index + 1);
    brands.push({
      brand,
      product: product || null,
      store: (store || null) as StoreSeed | null,
    });
  });
  return brands;
}

const literal = (text: string | null) =>
  text === null ? "null" : `'${text.replaceAll("'", "''")}'`;

export function toMigration(brands: Brand[]): string {
  const rows = [...brands]
    .sort((a, b) => {
      const [x, y] = [brandKey(a.brand), brandKey(b.brand)];
      return x < y ? -1 : x > y ? 1 : 0;
    })
    .map(({ brand, product, store }) =>
      `  (${literal(brand)}, ${literal(product)}, ${literal(store)})`
    );
  return [
    "-- Generated by supabase/classifier/generate_brands.ts from supabase/classifier/brands.tsv.",
    "-- Edit the TSV and generate a new migration; do not edit this file.",
    "",
    "truncate public.brands;",
    "",
    "insert into public.brands (brand, product, store_seed) values",
    rows.join(",\n") + ";",
    "",
  ].join("\n");
}

export const brandsUrl = new URL("./brands.tsv", import.meta.url);
export const migrationsUrl = new URL("../migrations/", import.meta.url);

if (import.meta.main) {
  const [target] = Deno.args;
  if (!target) {
    console.error("usage: generate_brands.ts <migration.sql>");
    Deno.exit(2);
  }
  const brands = parseBrands(await Deno.readTextFile(brandsUrl));
  await Deno.writeTextFile(target, toMigration(brands));
  console.log(`${brands.length} brands -> ${target}`);
}
