// Turns synonyms.tsv into the migration that loads public.classifier_synonyms (job 32a).
// Usage: deno run --allow-read --allow-write generate_synonyms.ts <migration.sql>
// Create the migration first (`supabase migration new classifier_synonyms`); a migration
// already on main is never edited.

import {
  dictionaryUrl,
  parseDictionary,
  refreshLexicon,
  type Term,
} from "./generate.ts";

export type Synonym = { variant: string; canonical: string };

const termPattern = /^[a-zäöüß]+( [a-zäöüß]+)*$/;

/**
 * Each line is variant<TAB>canonical. The canonical is a dictionary term and no variant itself;
 * a variant the dictionary lists has the canonical's category there.
 */
export function parseSynonyms(tsv: string, terms: Term[]): Synonym[] {
  const category = new Map(terms.map((t) => [t.term, t.category]));
  const seen = new Map<string, number>();
  const synonyms: Synonym[] = [];
  tsv.split("\n").forEach((raw, index) => {
    const line = raw.trimEnd();
    const at = `synonyms.tsv:${index + 1}`;
    if (line === "" || line.startsWith("#")) return;
    const fields = line.split("\t");
    if (fields.length !== 2) {
      throw new Error(`${at}: expected "variant<TAB>canonical"`);
    }
    const [variant, canonical] = fields;
    for (const term of fields) {
      if (!termPattern.test(term)) {
        throw new Error(`${at}: invalid term "${term}"`);
      }
    }
    if (variant === canonical) {
      throw new Error(`${at}: "${variant}" is its own canonical`);
    }
    const target = category.get(canonical);
    if (target === undefined) {
      throw new Error(
        `${at}: canonical "${canonical}" is not in dictionary.tsv`,
      );
    }
    const own = category.get(variant);
    if (own !== undefined && own !== target) {
      throw new Error(
        `${at}: "${variant}" is ${own} in dictionary.tsv, "${canonical}" is ${target}`,
      );
    }
    const first = seen.get(variant);
    if (first !== undefined) {
      throw new Error(`${at}: "${variant}" repeats line ${first}`);
    }
    seen.set(variant, index + 1);
    synonyms.push({ variant, canonical });
  });
  const variants = new Set(synonyms.map((s) => s.variant));
  for (const { variant, canonical } of synonyms) {
    if (variants.has(canonical)) {
      throw new Error(
        `synonyms.tsv: "${variant}" points to "${canonical}", itself a variant`,
      );
    }
  }
  return synonyms;
}

export function toMigration(synonyms: Synonym[]): string {
  const rows = [...synonyms]
    .sort((a, b) => a.variant < b.variant ? -1 : a.variant > b.variant ? 1 : 0)
    .map(({ variant, canonical }) => `  ('${variant}', '${canonical}')`);
  return [
    "-- Generated by supabase/classifier/generate_synonyms.ts from supabase/classifier/synonyms.tsv.",
    "-- Edit the TSV and generate a new migration; do not edit this file.",
    "",
    "delete from public.classifier_synonyms;",
    "",
    "insert into public.classifier_synonyms (variant, canonical) values",
    rows.join(",\n") + ";",
    "",
    refreshLexicon,
  ].join("\n");
}

export const synonymsUrl = new URL("./synonyms.tsv", import.meta.url);

if (import.meta.main) {
  const [target] = Deno.args;
  if (!target) {
    console.error("usage: generate_synonyms.ts <migration.sql>");
    Deno.exit(2);
  }
  const terms = parseDictionary(await Deno.readTextFile(dictionaryUrl));
  const synonyms = parseSynonyms(
    await Deno.readTextFile(synonymsUrl),
    terms,
  );
  await Deno.writeTextFile(target, toMigration(synonyms));
  console.log(`${synonyms.length} synonyms -> ${target}`);
}
