#!/usr/bin/env node
// Writes the hex shapes of the Android Home Screen widget (job 63) from the geometry and colours
// in design/tokens/hummlist.tokens.json. Glance cannot clip a view to a path, so the store pill
// and the Add button are nine-patch PNGs (light and dark): only the flat middle stretches, the
// hexagonal ends keep their 120° corners. The empty list's hex is a vector with colour
// resources, so it follows night mode by itself. Node only, no packages and no network.
//   node design/widget/build.mjs           writes the files
//   node design/widget/build.mjs --check   writes nothing, exits 1 when a file differs
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { roundedPolygon, check } from '../app-icon/geom.mjs';
import { Canvas, coverage, png } from '../app-icon/raster.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens/hummlist.tokens.json'), 'utf8'));
const resolve = (v) => (typeof v === 'string' && /^\{.+\}$/.test(v) ? resolve(v.slice(1, -1).split('.').reduce((n, k) => n[k], tokens).$value) : v);
const color = (mode, name) => resolve(tokens.color[mode][name].$value).hex.toLowerCase();
const TIP = resolve(tokens.shape.hex.tip.$value);
const REF_HEIGHT = resolve(tokens.shape.hex['reference-height'].$value).value;
const CORNER = resolve(tokens.shape.hex['corner-radius'].$value).value;
const BORDER = resolve(tokens.border.width.$value).value;

// xxxhdpi: Android scales the PNGs down for every lower density.
const SCALE = 4;
const RES = 'app/android/app/src/main/res';

// HexBorder.pathFor (app/lib/design/hex_border.dart): a horizontal hex in [0, w] x [0, h], moved
// outward by `outset` (inward when negative) as a parallel curve.
function hexShape(w, h, outset = 0, orientation = 'horizontal') {
  const along = outset / Math.sin(Math.atan(1 / (2 * TIP)));
  const across = orientation === 'horizontal' ? h : w;
  const radius = Math.max(0, (CORNER * across) / REF_HEIGHT + outset);
  if (orientation === 'horizontal') {
    const [l, t, r, b] = [-along, -outset, w + along, h + outset];
    const tip = Math.min(TIP * (b - t), (r - l) / 2);
    const cy = (t + b) / 2;
    return roundedPolygon([[l, cy], [l + tip, t], [r - tip, t], [r, cy], [r - tip, b], [l + tip, b]], radius);
  }
  const [l, t, r, b] = [-outset, -along, w + outset, h + along];
  const tip = Math.min(TIP * (r - l), (b - t) / 2);
  const cx = (l + r) / 2;
  return roundedPolygon([[cx, t], [r, t + tip], [r, b - tip], [cx, b], [l, b - tip], [l, t + tip]], radius);
}

// A nine-patch of a horizontal hex `height` dp tall with a `stroke` dp contour. The image is as
// narrow as the two ends plus a 1 dp flat middle, which is the only column that stretches; the
// two rows at the tips' height stretch for a text taller than the design (large font sizes).
// The content markers leave the ends plus `padX` dp free.
function ninePatch(height, stroke, padX, face, contour) {
  const h = height * SCALE;
  const sw = stroke * SCALE;
  const tip = TIP * h;
  // The corner arcs reach r / tan(60°) past each vertex along the flat side.
  const arc = ((CORNER * height) / REF_HEIGHT) * SCALE / Math.tan(Math.PI / 3);
  const end = Math.ceil(tip + arc) + 1;
  const mid = SCALE;
  const w = 2 * end + mid;
  const W = w + 2;
  const H = h + 2;
  const art = new Canvas(W, H);
  const at = [1, 1, 1];
  art.paint(coverage(W, H, hexShape(w, h).rings, at), contour);
  art.paint(coverage(W, H, hexShape(w, h, -sw).rings, at), face);
  const rgba = art.bytes();
  const mark = (x, y) => rgba.set([0, 0, 0, 255], (y * W + x) * 4);
  for (let x = 1 + end; x < 1 + end + mid; x++) mark(x, 0);
  for (const y of [h / 2, h / 2 + 1]) mark(0, y);
  const pad = Math.round(tip + padX * SCALE);
  for (let x = 1 + pad; x < W - 1 - pad; x++) mark(x, H - 1);
  for (let y = 1; y < H - 1; y++) mark(W - 1, y);
  return png(W, H, rgba);
}

// The two stretchable controls: the store pill (20 dp, the app's 28 px badge with its contour
// scaled down) and the Add button (32 dp with the full contour).
const PILL = { height: 20, stroke: (BORDER * 20) / 28, padX: 1 };
const BUTTON = { height: 32, stroke: BORDER, padX: 2 };

const f = (n) => Number(n.toFixed(2));

// The empty list's badge: a pointy-top lemon hex with the contour and the app icon's check.
function doneHex() {
  const w = 40;
  const h = 46;
  const outer = hexShape(w, h, 0, 'pointyTop');
  const inner = hexShape(w, h, -BORDER, 'pointyTop');
  const s = 18;
  const tick = check((w - s) / 2, h / 2 - 0.43 * s, s, 3.2);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/widget/build.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${w}dp"
    android:height="${h}dp"
    android:viewportWidth="${w}"
    android:viewportHeight="${h}">
    <path android:fillColor="@color/hl_border" android:pathData="${outer.d}"/>
    <path android:fillColor="@color/hl_honey" android:pathData="${inner.d}"/>
    <path android:fillColor="@color/hl_on_honey" android:pathData="${tick.d}"/>
</vector>
`;
}

function outputs() {
  const files = [[`${RES}/drawable/widget_done_hex.xml`, doneHex()]];
  for (const [mode, dir] of [['light', 'drawable-xxxhdpi'], ['dark', 'drawable-night-xxxhdpi']]) {
    files.push([`${RES}/${dir}/widget_pill.9.png`, ninePatch(PILL.height, PILL.stroke, PILL.padX, color(mode, 'surface-raised'), color(mode, 'border'))]);
    files.push([`${RES}/${dir}/widget_add_button.9.png`, ninePatch(BUTTON.height, BUTTON.stroke, BUTTON.padX, color(mode, 'honey'), color(mode, 'border'))]);
  }
  return files;
}

const checkOnly = process.argv.includes('--check');
let stale = 0;
for (const [path, content] of outputs()) {
  const file = join(root, path);
  const want = Buffer.from(content);
  if (existsSync(file) && readFileSync(file).equals(want)) continue;
  if (checkOnly) {
    console.error(`${path} is stale: run node design/widget/build.mjs`);
    stale++;
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, want);
    console.log(`wrote ${path}`);
  }
}
process.exit(stale ? 1 : 0);
