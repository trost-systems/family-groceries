#!/usr/bin/env python3
"""Writes app/lib/app/framework_date_data.dart: Flutter's date symbols and patterns for de and en.

flutter_localizations' global delegates initialize intl with the date data of every locale they
support, which keeps all of it in the web build (job 133). app/lib/app/framework_localizations.dart
initializes de and en only, from the file this script cuts out of the pinned Flutter SDK's
packages/flutter_localizations/lib/src/l10n/generated_date_localizations.dart, entries copied
verbatim. Rerun it after a Flutter upgrade; the flutter gate fails while the file is stale.
Idempotent: the same SDK gives the same bytes.

Usage: scripts/framework-l10n.py
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

LOCALES = ["de", "en"]
APP = Path(__file__).resolve().parent.parent / "app"
TARGET = APP / "lib/app/framework_date_data.dart"
SOURCE = "packages/flutter_localizations/lib/src/l10n/generated_date_localizations.dart"


def sdk() -> Path:
    flutter = shutil.which("flutter")
    if flutter is None:
        sys.exit("framework-l10n: flutter is not on PATH")
    return Path(flutter).resolve().parent.parent


def block(lines: list[str], start: str, locale: str) -> str:
    """The entry for locale inside the top-level map that starts at the line `start`."""
    first = lines.index(start)
    begin = next(i for i in range(first, len(lines)) if lines[i].startswith(f"  '{locale}': "))
    end = next(i for i in range(begin, len(lines)) if re.fullmatch(r"  [)}],", lines[i]))
    return "\n".join(lines[begin : end + 1])


def main() -> None:
    root = sdk()
    version = json.loads((root / "bin/cache/flutter.version.json").read_text())["frameworkVersion"]
    lines = (root / SOURCE).read_text().split("\n")
    symbols_start = "final Map<String, intl.DateSymbols> dateSymbols = <String, intl.DateSymbols>{"
    patterns_start = (
        "const Map<String, Map<String, String>> datePatterns = <String, Map<String, String>>{"
    )
    symbols = "\n".join(block(lines, symbols_start, locale) for locale in LOCALES)
    patterns = "\n".join(block(lines, patterns_start, locale) for locale in LOCALES)
    TARGET.write_text(
        f"""// Generated by scripts/framework-l10n.py from Flutter {version}'s
// flutter_localizations/lib/src/l10n/generated_date_localizations.dart. Do not edit; rerun the
// script after a Flutter upgrade.

import 'package:intl/date_symbols.dart' as intl;

/// Flutter's date symbols for the app's languages.
final dateSymbols = <String, intl.DateSymbols>{{
{symbols}
}};

/// Flutter's date patterns (skeleton to format) for the app's languages.
const datePatterns = <String, Map<String, String>>{{
{patterns}
}};
"""
    )
    subprocess.run(
        [str(root / "bin/dart"), "format", str(TARGET)],
        cwd=APP,
        check=True,
        stdout=subprocess.DEVNULL,
    )


if __name__ == "__main__":
    main()
