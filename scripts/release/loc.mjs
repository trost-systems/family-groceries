// Lines of code of one commit, for the release record's `stats.loc` (releases/README.md, "Lines of
// code"). Read from git objects only, never the working tree, so the same commit always gives the
// same numbers. Plain node, no packages.
import process from 'node:process';
import { execFileSync } from 'node:child_process';

// The languages counted, by file extension. Everything else (Markdown, JSON, YAML, XML, images,
// fonts) is not code here.
export const LANGUAGES = {
  Dart: ['.dart'],
  TypeScript: ['.ts', '.tsx', '.mts', '.cts'],
  JavaScript: ['.js', '.mjs', '.cjs', '.jsx'],
  SQL: ['.sql'],
  Shell: ['.sh', '.bash'],
  Swift: ['.swift'],
  Kotlin: ['.kt', '.kts'],
  Python: ['.py'],
  Ruby: ['.rb'],
  'C/C++': ['.c', '.cc', '.cpp', '.h', '.hpp'],
  CSS: ['.css'],
  HTML: ['.html'],
};
const BY_EXTENSION = new Map(Object.entries(LANGUAGES).flatMap(([language, extensions]) => extensions.map((e) => [e, language])));

// Paths that are not the project's own source: docs (design prototypes among them), the
// gen-l10n output, goldens, the vendored PostHog web SDK, lockfiles and minified files.
const EXCLUDED = [
  /^docs\//,
  /^app\/lib\/l10n\//,
  /(^|\/)goldens\//,
  /^app\/web\/posthog\//,
  /(^|\/)(package-lock\.json|[^/]*\.lock)$/,
  /\.min\.(js|css)$/,
  /\.(g|freezed|mocks)\.dart$/,
];
// A generator's header in the first lines ("Generated by …. Do not edit.") marks a generated file.
const GENERATED_HEAD = 5;
const isGenerated = (text) => {
  const head = text.split('\n', GENERATED_HEAD).join('\n');
  return /generated/i.test(head) && /do not edit/i.test(head);
};

export const languageOf = (path) => {
  if (EXCLUDED.some((re) => re.test(path))) return null;
  const dot = path.lastIndexOf('.');
  return dot > path.lastIndexOf('/') ? (BY_EXTENSION.get(path.slice(dot).toLowerCase()) ?? null) : null;
};

// Lines with anything but white space on them.
export const codeLines = (text) => text.split('\n').filter((line) => line.trim() !== '').length;

const run = (cwd, args, input) => execFileSync('git', args, { cwd, input, maxBuffer: 1 << 30, stdio: ['pipe', 'pipe', 'pipe'] });

// `{ total, languages: [{ language, files, lines }] }` for the tree of `sha`, most lines first.
export function linesOfCode(sha, { cwd = process.cwd() } = {}) {
  const entries = run(cwd, ['ls-tree', '-r', '-z', '--full-tree', sha])
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .map((line) => {
      const [meta, path] = line.split('\t');
      const [mode, type, object] = meta.split(' ');
      return { mode, type, object, path };
    })
    // Regular files only: no symlinks (120000), no submodules (commit entries).
    .filter((e) => e.type === 'blob' && e.mode !== '120000')
    .map((e) => ({ ...e, language: languageOf(e.path) }))
    .filter((e) => e.language);
  const counts = new Map();
  if (entries.length > 0) {
    const out = run(cwd, ['cat-file', '--batch'], `${entries.map((e) => e.object).join('\n')}\n`);
    let at = 0;
    for (const entry of entries) {
      const header = out.indexOf(0x0a, at);
      const size = Number(out.toString('latin1', at, header).split(' ')[2]);
      const blob = out.subarray(header + 1, header + 1 + size);
      at = header + 1 + size + 1;
      // Binary content (a NUL byte) is no source code, whatever its name.
      if (blob.includes(0)) continue;
      const text = blob.toString('utf8');
      if (isGenerated(text)) continue;
      const count = counts.get(entry.language) ?? { language: entry.language, files: 0, lines: 0 };
      count.files += 1;
      count.lines += codeLines(text);
      counts.set(entry.language, count);
    }
  }
  const languages = [...counts.values()].sort((a, b) => b.lines - a.lines || (a.language < b.language ? -1 : 1));
  return { total: languages.reduce((sum, l) => sum + l.lines, 0), languages };
}
