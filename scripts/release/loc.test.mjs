// loc.mjs against a scratch git repository: what counts as code, what is left out, and that a
// commit gives the same numbers whatever the working tree holds. Run by scripts/release/test.sh.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, before, test } from 'node:test';
import { codeLines, languageOf, linesOfCode } from './loc.mjs';

let repo;
const shas = {};
const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();

function commit(name, files) {
  for (const [path, content] of Object.entries(files)) {
    const file = join(repo, path);
    if (content === null) rmSync(file);
    else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
  }
  git('add', '-A');
  execFileSync('git', ['-c', 'user.name=T', '-c', 'user.email=t@example.com', 'commit', '-q', '-m', name], {
    cwd: repo,
    env: { ...process.env, GIT_AUTHOR_DATE: '2026-10-22T10:00:00+02:00', GIT_COMMITTER_DATE: '2026-10-22T10:00:00+02:00' },
  });
  shas[name] = git('rev-parse', 'HEAD');
}

before(() => {
  repo = mkdtempSync(join(tmpdir(), 'loc-test-'));
  git('init', '-q', '-b', 'main');
  commit('first', {
    'app/lib/main.dart': "import 'x';\n\nvoid main() {\n  run();\n}\n",
    'app/lib/l10n/app_localizations.dart': 'class L {}\nclass M {}\n',
    'app/lib/design/tokens.g.dart': 'const a = 1;\n',
    'app/lib/list/lexicon.dart': '// Generated by a script from the lexicon.\n// Do not edit; rerun it.\nconst words = [];\n',
    'app/lib/late_marker.dart': 'a();\nb();\nc();\nd();\ne();\n// Generated by hand, do not edit.\n',
    'app/test/goldens/list.dart': 'x();\n',
    'app/web/posthog/array.js': 'vendored();\n',
    'docs/design/proto/app.tsx': 'export const A = 1;\n',
    'supabase/functions/api/index.ts': 'export {};\n   \n\t\nconst a = 1;\r\nconst b = 2;',
    'site/build.mjs': 'build();\n',
    'site/public/app.min.js': 'a();\n',
    'site/public/styles.css': 'a { b: c; }\n',
    'scripts/dev.sh': '#!/bin/sh\necho hi\n',
    'supabase/migrations/1_init.sql': 'create table t ();\n',
    'site/package-lock.json': '{}\n',
    'app/pubspec.lock': 'x\n',
    'README.md': '# Readme\n\ntext\n',
    'app/assets/data.js': Buffer.from('a();\n\0\x01binary'),
    'Makefile': 'all:\n\techo\n',
  });
  symlinkSync('main.dart', join(repo, 'app/lib/link.dart'));
  commit('second', { 'app/lib/main.dart': "import 'x';\n\nvoid main() {}\n", 'scripts/dev.sh': null, 'app/lib/extra.DART': 'y();\n' });
});

after(() => rmSync(repo, { recursive: true, force: true }));

test('languageOf maps extensions and leaves out docs, l10n output, goldens, vendored, lock and minified files', () => {
  assert.equal(languageOf('app/lib/main.dart'), 'Dart');
  assert.equal(languageOf('app/lib/MAIN.DART'), 'Dart');
  assert.equal(languageOf('supabase/functions/api/index.ts'), 'TypeScript');
  assert.equal(languageOf('e2e/tests/a.spec.tsx'), 'TypeScript');
  assert.equal(languageOf('site/build.mjs'), 'JavaScript');
  assert.equal(languageOf('app/linux/runner/main.cc'), 'C/C++');
  for (const path of [
    'docs/design/x.tsx',
    'app/lib/l10n/app_localizations_de.dart',
    'app/test/design/goldens/a.dart',
    'app/web/posthog/array.js',
    'site/package-lock.json',
    'app/pubspec.lock',
    'a/b.min.js',
    'app/lib/design/tokens.g.dart',
    'app/lib/x.freezed.dart',
    'README.md',
    'Makefile',
    'app/.dart/thing',
    'site/vercel.json',
  ]) {
    assert.equal(languageOf(path), null, path);
  }
});

test('codeLines counts lines with anything but white space', () => {
  assert.equal(codeLines(''), 0);
  assert.equal(codeLines('\n\n  \n\t\n'), 0);
  assert.equal(codeLines('a\nb'), 2, 'a last line without a newline counts');
  assert.equal(codeLines('a\r\n\r\nb\r\n'), 2);
});

test('linesOfCode counts the tracked source of a commit by language, most lines first', () => {
  assert.deepEqual(linesOfCode(shas.first, { cwd: repo }), {
    total: 18,
    languages: [
      { language: 'Dart', files: 2, lines: 10 },
      { language: 'TypeScript', files: 1, lines: 3 },
      { language: 'Shell', files: 1, lines: 2 },
      { language: 'CSS', files: 1, lines: 1 },
      // site/build.mjs only: the minified, vendored and binary .js files are left out.
      { language: 'JavaScript', files: 1, lines: 1 },
      { language: 'SQL', files: 1, lines: 1 },
    ].sort((a, b) => b.lines - a.lines || (a.language < b.language ? -1 : 1)),
  });
});

test('generated headers, symlinks and later commits: each commit its own tree', () => {
  const second = linesOfCode(shas.second, { cwd: repo });
  const dart = second.languages.find((l) => l.language === 'Dart');
  // main.dart (2), extra.DART (1), late_marker.dart (6: its marker is below the first 5 lines);
  // lexicon.dart has a generator header; link.dart is a symlink.
  assert.deepEqual(dart, { language: 'Dart', files: 3, lines: 9 });
  assert.equal(second.languages.find((l) => l.language === 'Shell'), undefined, 'scripts/dev.sh was deleted');
  assert.equal(second.total, second.languages.reduce((sum, l) => sum + l.lines, 0));
});

test('the working tree does not matter, only the commit', () => {
  const before = linesOfCode(shas.first, { cwd: repo });
  writeFileSync(join(repo, 'app/lib/main.dart'), 'a\n'.repeat(1000));
  writeFileSync(join(repo, 'untracked.dart'), 'a\n'.repeat(1000));
  assert.deepEqual(linesOfCode(shas.first, { cwd: repo }), before);
  assert.deepEqual(linesOfCode(shas.first, { cwd: repo }), before, 'twice the same');
  git('checkout', '-q', '--', '.');
  rmSync(join(repo, 'untracked.dart'));
});

test('an empty tree has no lines', () => {
  const empty = git('hash-object', '-t', 'tree', '-w', '/dev/null');
  assert.deepEqual(linesOfCode(empty, { cwd: repo }), { total: 0, languages: [] });
});
