import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
import { chromium } from '/workspace/hummlist/research/design-prototypes/_tools/node_modules/playwright/index.mjs';
const root = '/workspace/hummlist/research/design-prototypes/option-2-wochenmarkt';
const T = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' };
const srv = createServer((q, r) => { const f = join(root, decodeURIComponent(new URL(q.url, 'http://x').pathname)); if (!existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'Content-Type': T[extname(f)] || 'application/octet-stream' }); r.end(readFileSync(f)); }).listen(0);
await new Promise((r) => srv.once('listening', r));
const base = `http://127.0.0.1:${srv.address().port}`;
const b = await chromium.launch();
const [page, w, scheme, prefix, chunk] = process.argv.slice(2);
const ctx = await b.newContext({ viewport: { width: +w, height: 900 }, colorScheme: scheme });
const p = await ctx.newPage();
await p.goto(`${base}/${page}`, { waitUntil: 'networkidle' });
await p.evaluate(() => document.fonts.ready);
const H = await p.evaluate(() => document.documentElement.scrollHeight);
const step = +chunk || 1100;
for (let y = 0, i = 0; y < H; y += step, i++) await p.screenshot({ path: `/tmp/wochenmarkt-shots/${prefix}-${i}.png`, clip: { x: 0, y, width: +w, height: Math.min(step, H - y) }, fullPage: true });
console.log(H);
await b.close(); srv.close();
