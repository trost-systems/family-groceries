// Usage: node build-hex-variants.mjs
// Merges option-3-hummel/tokens.json with _tokens/hummel-hex.tokens.json into one
// tokens.json per Hummel Hex variant (common groups plus variant.<name>), then writes
// each variant's tokens.css through build-css.mjs. The variant folders must exist.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { buildCss } from './build-css.mjs';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const isGroup = (v) => v && typeof v === 'object' && !Array.isArray(v) && !('$value' in v);
function merge(a, b) {
  const out = { ...a };
  for (const [k, v] of Object.entries(b)) out[k] = isGroup(v) && isGroup(a[k]) ? merge(a[k], v) : v;
  return out;
}

const hex = read('_tokens/hummel-hex.tokens.json');
const { variant, $description, $extensions, ...common } = hex;
const meta = $extensions['com.hummlist'];
const base = read(`${meta.base}/tokens.json`);
for (const [name, folder] of Object.entries(meta.variants)) {
  const tokens = merge(merge(base, common), variant[name]);
  tokens.$description = `Hummlist design tokens, ${folder}: ${meta.base} plus _tokens/hummel-hex.tokens.json (common + variant.${name}). Generated by _tools/build-hex-variants.mjs. Do not edit.`;
  tokens.$extensions = { 'com.hummlist': { ...base.$extensions['com.hummlist'], option: folder, variant: name } };
  const dir = join(root, folder);
  writeFileSync(join(dir, 'tokens.json'), `${JSON.stringify(tokens, null, 2)}\n`);
  writeFileSync(join(dir, 'tokens.css'), await buildCss(dir));
  console.log(`${folder}: tokens.json + tokens.css`);
}
